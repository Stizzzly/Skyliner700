"""Generate an indexed aircraft mesh from the retained original triangle soup.
Run without arguments to regenerate src/plane.inc; --check verifies reproducibility.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
points=[tuple(map(int,p)) for p in re.findall(r'\{(-?\d+),(-?\d+),(-?\d+)\}',(root/'tests/reference_renderer/plane.inc').read_text())]
unique=[];indices=[]
for point in points:
    if point not in unique:unique.append(point)
    indices.append(unique.index(point))
assert len(points)==84 and len(unique)==35 and len(unique)<256
text='/* Indexed geometry extracted from upstream model/plane.c; MIT. */\n'
text+='/* Generated by tests/generate_plane.py; triangle order/material split retained. */\n'
text+='struct PlanePoint { int x,y,z; };\nstatic const PlanePoint plane[]={\n'
text+=''.join('{%d,%d,%d},\n'%p for p in unique)+'};\n'
text+='static const unsigned char planeIndices[]={\n'
text+=''.join(','.join(map(str,indices[i:i+12]))+',\n' for i in range(0,len(indices),12))+'};\n'
text+='enum { PLANE_VERTEX_COUNT=sizeof(plane)/sizeof(plane[0]), PLANE_COUNT=sizeof(planeIndices)/sizeof(planeIndices[0]) };\n'
path=root/'src/plane.inc'
if '--check' in sys.argv:
    assert path.read_text()==text,'Regenerate indexed aircraft geometry'
else:path.write_text(text)
print('PASS: 84 aircraft indices reconstruct all original triangles from 35 unique vertices.')
